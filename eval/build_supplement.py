"""Build the supplementary tables for the RareMCP paper (eval/results/SUPPLEMENT.md) from saved results."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "eval/results"
RUNS = {"base": {"Sonnet": "v1-sonnet", "Haiku": "v1-haiku"}, "hard": {"Sonnet": "hard-sonnet", "Haiku": "hard-haiku"}}
CONDS = [("no_tools", "No tools"), ("web_search", "Web search"), ("biomcp_go", "BioMCP"), ("biomcp", "RareMCP 0.1.0")]


def summ(run, prefix="all_"):
    return json.loads((RES / run / f"{prefix}summary.json").read_text())


def main() -> int:
    L = ["# Supplementary Information: RareMCP evaluation", "", "Generated by `eval/build_supplement.py` from `eval/results/`.", ""]
    # Supplementary Table 1: per-template accuracy
    L += ["## Supplementary Table 1. Accuracy by template, condition and model (gold v1.1, all questions)", "",
          "| Tier | Template | n | " + " | ".join(f"{c} (S/H)" for _, c in CONDS) + " | RareMCP 0.1.1 (S/H) |", "|---|---|---|" + "---|" * (len(CONDS) + 1)]
    fix = {m: summ(f"fda011-{m.lower()}")["by_template"] for m in ("Sonnet", "Haiku")}
    for tier, runs in RUNS.items():
        bt = {m: summ(r)["by_template"] for m, r in runs.items()}
        for t in bt["Sonnet"]:
            def acc(m, cond, src=bt, t=t):
                v = src[m].get(t, {})
                x = next((x for k, x in v.items() if k.split("|")[1] == cond), None)
                return "–" if x is None else f"{100 * x['accuracy']:.0f}"
            n = next(iter(bt["Sonnet"][t].values()))["n"]
            cells = [f"{acc('Sonnet', c)}/{acc('Haiku', c)}" for c, _ in CONDS]
            f11 = f"{acc('Sonnet', 'biomcp', fix)}/{acc('Haiku', 'biomcp', fix)}" if t in fix["Sonnet"] else "–"
            L.append(f"| {tier} | {t} | {n} | " + " | ".join(cells) + f" | {f11} |")
    # Supplementary Table 2: original gold
    L += ["", "## Supplementary Table 2. Accuracy against the original gold answers (v1.0) and the audited gold (v1.1)", "",
          "| Tier | Model | Condition | v1.0 | v1.1 |", "|---|---|---|---|---|"]
    for tier, runs in RUNS.items():
        for m, r in runs.items():
            a, b = summ(r, "v1gold_all_")["by_condition"], summ(r)["by_condition"]
            for cond, name in CONDS:
                k = next((k for k in b if k.split("|")[1] == cond), None)
                if k:
                    L.append(f"| {tier} | {m} | {name} | {100 * a[k]['accuracy']:.1f}% | {100 * b[k]['accuracy']:.1f}% |")
    # S3 accuracy by population (rare disease, NTD, EU-rarity items); exploratory
    qs = {}
    for f in ("eval/questions.jsonl", "eval/questions_hard.jsonl"):
        for line in (ROOT / f).read_text().splitlines():
            if line.strip():
                q = json.loads(line)
                qs[q["id"]] = q
    ntd_t = {q["template"] for q in qs.values() if q.get("population") == "NTD"}
    cnt: dict = {}
    for runs in RUNS.values():
        for m, r in runs.items():
            for line in (RES / r / "all_scored.jsonl").read_text().splitlines():
                x = json.loads(line)
                if x.get("error"):
                    continue
                q = qs[x["qid"]]
                pop = {"NTD": "NTD", "rare": "Rare disease"}.get(q.get("population"), "EU-rarity items (10 rare, 10 not)")
                keys = [(pop, m, x["condition"])]
                if pop == "Rare disease" and q["template"] in ntd_t:
                    keys.append(("Rare disease, NTD templates only", m, x["condition"]))
                for k in keys:
                    c = cnt.setdefault(k, [0, 0])
                    c[0] += bool(x["correct"])
                    c[1] += 1
    L += ["", "## Supplementary Table 3. Accuracy by population, condition and model (gold v1.1, all 314 questions, RareMCP 0.1.0; exploratory)", "",
          "NTD questions come only from aggregate templates; the 'NTD templates only' row restricts rare-disease questions to those templates.", "",
          "| Population | n | " + " | ".join(f"{c} (S/H)" for _, c in CONDS) + " |", "|---|---|" + "---|" * len(CONDS)]
    for pop in ("Rare disease", "Rare disease, NTD templates only", "NTD", "EU-rarity items (10 rare, 10 not)"):
        n = cnt[(pop, "Sonnet", "biomcp")][1]
        cells = []
        for cond, _ in CONDS:
            s_, h_ = cnt[(pop, "Sonnet", cond)], cnt[(pop, "Haiku", cond)]
            cells.append(f"{100 * s_[0] / s_[1]:.1f} / {100 * h_[0] / h_[1]:.1f}")
        L.append(f"| {pop} | {n} | " + " | ".join(cells) + " |")
    # Supplementary Table 4: gold corrections
    gc = json.loads((ROOT / "eval/gold_corrections_v1_1.json").read_text())
    L += ["", "## Supplementary Table 4. Gold answers corrected in v1.1", "", f"Rule: {gc['rule']}.", "", "| Question | Template | v1.0 | v1.1 | Evidence |", "|---|---|---|---|---|"]
    for q, c in gc["corrections"].items():
        L.append(f"| {q} | {c['template']} | {json.dumps(c['old'])} | {json.dumps(c['new'])} | {c['evidence'][:220].replace('|', '/')} |")
    # Supplementary Table 5: fabrication excerpts
    pf = RES / "PROCESS_FABRICATION.md"
    L += ["", "## Supplementary Table 5. Fabricated tool-use excerpts (no-tools condition)", "", pf.read_text().split("## Flagged excerpts (confirm manually)")[-1].strip()]
    # Supplementary Table 6: why web search was wrong (staleness check, eval/staleness_check.py)
    ws = RES / "WEB_STALENESS.json"
    if ws.exists():
        d = json.loads(ws.read_text())
        rows = d["rows"]
        cats = ["abstained", "not retrieved", "source disagrees", "gold retrieved", "yes/no judgement, prevalence retrieved",
                "yes/no judgement, no prevalence retrieved", "yes/no judgement"]
        L += ["", f"## Supplementary Table 6. Causes of incorrect web-search answers ({len(rows)} answers, both models, gold v1.1)", "",
              "| Category | Definition | n | % |", "|---|---|---|---|"]
        defs = {"abstained": "Model reported that it could not find the answer",
                "not retrieved": "Neither the gold nor the given answer appeared in the retrieved text",
                "source disagrees": "Retrieved text supported the given answer but not the gold (possible staleness)",
                "gold retrieved": "Retrieved text contained the gold answer; the error was in reading or reasoning",
                "yes/no judgement, prevalence retrieved": "EU-rarity item; a prevalence figure was retrieved",
                "yes/no judgement, no prevalence retrieved": "EU-rarity item; no prevalence figure was retrieved",
                "yes/no judgement": "Other yes/no item (string matching not informative)"}
        for c in cats:
            n = sum(r["category"] == c for r in rows)
            if n:
                L.append(f"| {c[0].upper() + c[1:]} | {defs[c]} | {n} | {100 * n / len(rows):.0f} |")
    (RES / "SUPPLEMENT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {RES / 'SUPPLEMENT.md'} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
