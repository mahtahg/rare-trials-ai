"""Cross-run comparison: tier x model x condition, tool benefit per model, and Haiku-vs-Sonnet benefit gap.

Reads eval/results/<run>/scored.jsonl (errored runs are already excluded by score.py) and writes
eval/results/COMPARISON.md and COMPARISON.json. Paired analyses use the questions answered in every
cell being compared. Uncertainty: Wilson CIs for proportions, exact McNemar for paired binary
comparisons, question-level paired bootstrap for differences and difference-in-differences.

    python eval/compare.py
"""

from __future__ import annotations

import json
import random
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "eval"))
from score import mcnemar_exact, wilson

RES = ROOT / "eval/results"
TIERS = {"v1-": "base", "hard-": "hard"}
CONDS = ["no_tools", "web_search", "biomcp"]


def short(m: str) -> str:
    return m.replace("claude-", "").replace("-5-5", "")


def load(prefix: str = ""):
    cells = defaultdict(dict)  # (tier, model, cond) -> {qid: correct}
    for d in sorted(RES.iterdir()):
        f = d / f"{prefix}scored.jsonl"
        tier = next((t for p, t in TIERS.items() if d.name.startswith(p)), None)
        if not f.exists() or tier is None:
            continue
        for line in f.open():
            x = json.loads(line)
            if x.get("error"):
                continue
            cells[(tier, x["model"], x["condition"])][x["qid"]] = bool(x["correct"])
    return cells


def boot(fn, qids, iters=10000, seed=7):
    rng = random.Random(seed)
    n = len(qids)
    est = fn(qids)
    draws = sorted(fn([qids[rng.randrange(n)] for _ in range(n)]) for _ in range(iters))
    return round(est, 4), round(draws[int(0.025 * iters)], 4), round(draws[int(0.975 * iters)], 4)


def main() -> int:
    prefix = sys.argv[1] if len(sys.argv) > 1 else ""
    cells = load(prefix)
    out = {"cells": [], "benefit": [], "benefit_gap": [], "model_paired": []}
    md = ["# Cross-run comparison" + (" (all questions, before review exclusions)" if prefix else " (reviewed question set)"), "", "Generated by `eval/compare.py`. Errored runs excluded; paired rows use shared questions only.", ""]
    tiers = sorted({k[0] for k in cells}, key=["base", "hard"].index)
    for tier in tiers:
        models = sorted({k[1] for k in cells if k[0] == tier})
        md += [f"## {tier} tier", "", "| model | condition | n | accuracy (95% CI) |", "|---|---|---|---|"]
        for m in models:
            for c in CONDS:
                v = cells.get((tier, m, c))
                if not v:
                    continue
                k, n = sum(v.values()), len(v)
                lo, hi = wilson(k, n)
                out["cells"].append({"tier": tier, "model": m, "condition": c, "n": n, "acc": round(k / n, 4), "ci": [lo, hi]})
                md.append(f"| {short(m)} | {c} | {n} | {k / n:.3f} ({lo:.3f}–{hi:.3f}) |")
        md += ["", "**Tool benefit (paired, same questions)**", "",
               "| model | comparison | n | biomcp-only | other-only | McNemar p | Δacc (95% CI) |", "|---|---|---|---|---|---|---|"]
        for m in models:
            for other in ("no_tools", "web_search"):
                a, b = cells.get((tier, m, "biomcp")), cells.get((tier, m, other))
                if not a or not b:
                    continue
                q = sorted(set(a) & set(b))
                bo = sum(a[i] and not b[i] for i in q)
                oo = sum(b[i] and not a[i] for i in q)
                d = boot(lambda s, a=a, b=b: sum(a[i] - b[i] for i in s) / len(s), q)
                p = mcnemar_exact(bo, oo)
                out["benefit"].append({"tier": tier, "model": m, "vs": other, "n": len(q), "b": bo, "c": oo, "p": p, "delta": d})
                md.append(f"| {short(m)} | biomcp vs {other} | {len(q)} | {bo} | {oo} | {p:.3g} | {d[0]:+.3f} ({d[1]:+.3f}, {d[2]:+.3f}) |")
        if len(models) >= 2:
            md += ["", "**Does the smaller model gain more from tools? (difference-in-differences, paired bootstrap)**", "",
                   "| contrast | n | gain(Haiku) − gain(Sonnet) (95% CI) |", "|---|---|---|"]
            hk = next((m for m in models if "haiku" in m), None)
            sn = next((m for m in models if "sonnet" in m), None)
            if hk and sn:
                for other in ("no_tools", "web_search"):
                    cs = [cells.get((tier, x, y)) for x in (hk, sn) for y in ("biomcp", other)]
                    if not all(cs):
                        continue
                    hb, ho, sb, so = cs
                    q = sorted(set.intersection(*(set(c) for c in cs)))
                    d = boot(lambda s, hb=hb, ho=ho, sb=sb, so=so: sum((hb[i] - ho[i]) - (sb[i] - so[i]) for i in s) / len(s), q)
                    out["benefit_gap"].append({"tier": tier, "vs": other, "n": len(q), "did": d})
                    md.append(f"| biomcp vs {other} | {len(q)} | {d[0]:+.3f} ({d[1]:+.3f}, {d[2]:+.3f}) |")
                md += ["", "**Haiku vs Sonnet within condition (paired)**", "",
                       "| condition | n | Haiku-only | Sonnet-only | McNemar p | Δacc Haiku−Sonnet (95% CI) |", "|---|---|---|---|---|---|"]
                for c in CONDS:
                    a, b = cells.get((tier, hk, c)), cells.get((tier, sn, c))
                    if not a or not b:
                        continue
                    q = sorted(set(a) & set(b))
                    ho_ = sum(a[i] and not b[i] for i in q)
                    so_ = sum(b[i] and not a[i] for i in q)
                    d = boot(lambda s, a=a, b=b: sum(a[i] - b[i] for i in s) / len(s), q)
                    out["model_paired"].append({"tier": tier, "condition": c, "n": len(q), "haiku_only": ho_, "sonnet_only": so_,
                                                "p": mcnemar_exact(ho_, so_), "delta": d})
                    md.append(f"| {c} | {len(q)} | {ho_} | {so_} | {mcnemar_exact(ho_, so_):.3g} | {d[0]:+.3f} ({d[1]:+.3f}, {d[2]:+.3f}) |")
        md.append("")
    (RES / f"{prefix}COMPARISON.md").write_text("\n".join(md) + "\n")
    (RES / f"{prefix}COMPARISON.json").write_text(json.dumps(out, indent=1))
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
